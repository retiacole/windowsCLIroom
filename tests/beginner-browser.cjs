'use strict';
const assert = require('node:assert/strict');
const fs = require('node:fs');
const path = require('node:path');
const http = require('node:http');
const {chromium} = require('playwright');
const Data = require('../src/data.js');
const root = path.resolve(__dirname,'..');
const output = path.join(root,'test-artifacts');

(async()=>{
  const server = http.createServer((req,res)=>{res.writeHead(200,{'Content-Type':'text/html; charset=utf-8'});res.end(fs.readFileSync(path.join(root,'windowsCLIroom.html')));});
  await new Promise(resolve=>server.listen(0,'127.0.0.1',resolve));
  let browser;
  try {
    browser=await chromium.launch({headless:true,...(process.env.WCR_BROWSER_CHANNEL?{channel:process.env.WCR_BROWSER_CHANNEL}:{})});
    const context=await browser.newContext({viewport:{width:1440,height:1000}}),page=await context.newPage(),errors=[];
    page.on('pageerror',e=>errors.push(e.message));page.on('dialog',d=>d.accept());
    await page.goto(`http://127.0.0.1:${server.address().port}/`);
    await page.locator('.hero-actions [data-open]').click();
    const input=()=>page.locator('#command-input');
    const run=async command=>{await input().fill(command);await input().press('Enter');};
    const open=async id=>page.locator(`.lesson-item[data-open="${id}"]`).click();
    const answer=async id=>{const l=Data.lessons.find(l=>l.id===id);if(l.question)await page.locator(`input[name="answer"][value="${l.question.answer}"]`).check();await page.locator('#check-button').click();};
    const current=()=>page.evaluate(()=>{const s=JSON.parse(localStorage.getItem(WCREngine.KEY));return s.checkpoints[s.activeId];});
    const success=async id=>assert.equal(await page.locator('#feedback .success').count(),1,id);

    await open('current-directory');await page.locator('#check-button').click();
    assert.ok(await page.locator('.condition-list [data-ok="false"]').count());
    await run('cd');
    assert.ok(await page.locator('.condition-list [data-ok="true"]').count());
    assert.ok(await page.locator('.condition-list [data-ok="false"]').count());
    await page.screenshot({path:path.join(output,'beginner-checklist-ja.png'),fullPage:true});
    const cpBefore=(await current());
    await page.locator('#language-button').click();
    assert.equal(await page.locator('.completion-checklist h3').textContent(),'Completion checklist');
    assert.deepEqual(await current(),cpBefore,'checklist language switch leaves learner data intact');
    await page.locator('#language-button').click();
    await run('cd C:\\Lab');await success('L02 without /d');
    await open('drives-and-parent');
    for(const command of ['cd /d D:\\Support','type ticket.txt','cd..'])await run(command);
    await success('L03 compact cd..');
    await open('stop-one-app');
    for(const command of ['tasklist','taskkill /PID 4320'])await run(command);
    await answer('stop-one-app');await success('L16 unfiltered tasklist');
    await open('start-print-service');
    for(const command of ['sc.exe query Spooler','net start "Print Spooler"','sc.exe query Spooler'])await run(command);
    await answer('start-print-service');await success('L49 display name');

    await open('quoted-path');
    const draft='type “C:¥Lab¥Shared Files¥guide.txt”';
    await input().fill(draft);
    assert.equal(await page.locator('#input-warning').isVisible(),true);
    assert.match(await page.locator('#input-warning').textContent(),/半角/);
    assert.equal((await current()).session.history.length,0,'warning appears before execution');
    await page.locator('#language-button').click();
    assert.match(await page.locator('#input-warning').textContent(),/ASCII|half.width/i);
    assert.equal(await input().inputValue(),draft);
    await page.locator('#language-button').click();
    await page.setViewportSize({width:390,height:844});
    await page.locator('#input-warning').scrollIntoViewIfNeeded();
    assert.equal(await page.evaluate(()=>document.documentElement.scrollWidth<=innerWidth),true);
    await page.screenshot({path:path.join(output,'beginner-input-mobile.png'),fullPage:true});
    await page.setViewportSize({width:1440,height:1000});
    await input().press('Enter');
    assert.equal((await current()).session.history.at(-1).line,draft);
    assert.match(await page.locator('#console-output').textContent(),/半角/);
    await input().press('ArrowUp');
    assert.equal(await input().inputValue(),draft);
    assert.equal(await page.locator('#input-warning').isVisible(),true);
    await input().fill('type "C:¥Lab¥Shared Files¥guide.txt"');
    assert.equal(await page.locator('#input-warning').isVisible(),false);
    await input().press('Enter');await success('L05 corrected quotes');

    await open('save-and-append');
    await run('echo PC-014 ＞ C:¥Lab¥Reports¥notes.txt');
    assert.equal((await current()).session.files['c:\\lab\\reports\\notes.txt'],undefined);
    assert.ok(await page.locator('.condition-list [data-check-kind="file"][data-ok="false"]').count());
    assert.match(await page.locator('.completion-checklist').textContent(),/notes\.txt/);
    await run('echo PC-014 > C:¥Lab¥Reports¥notes.txt');
    assert.ok(await page.locator('.condition-list [data-check-kind="file"][data-ok="false"]').count());
    await page.screenshot({path:path.join(output,'beginner-file-checklist.png'),fullPage:true});
    await run('echo Printer issue >> C:¥Lab¥Reports¥notes.txt');
    assert.equal(await page.locator('.condition-list [data-check-kind="file"][data-ok="false"]').count(),0);
    assert.ok(await page.locator('.condition-list [data-check-kind="command"][data-ok="false"]').count());
    await run('type C:¥Lab¥Reports¥notes.txt');await success('L09 all checklist conditions');

    await page.locator('#sandbox-button').click();
    await run('echo 日本語の本文 “引用” ＞ 全角 > C:¥Lab¥Reports¥literal.txt');
    assert.equal((await current()).session.files['c:\\lab\\reports\\literal.txt'].content,'日本語の本文 “引用” ＞ 全角\n');
    await run('dir　C:¥Lab');
    assert.notEqual((await current()).session.history.at(-1).code,0);
    assert.match((await current()).session.history.at(-1).stderr,/半角/);
    await run('cls');
    assert.equal(await page.locator('#console-output .history-entry').count(),0,'valid cls clears visible history');
    await run('cls　');
    assert.notEqual((await current()).session.history.at(-1).code,0);
    assert.match(await page.locator('#console-output .history-entry').last().textContent(),/半角/,'invalid full-width cls keeps its diagnostic visible');
    assert.deepEqual(errors,[]);
    console.log('Beginner browser checks passed: accepted alternatives, live input guidance, unchanged literal text, bilingual checklists and mobile layout.');
  }finally{if(browser)await browser.close();await new Promise(resolve=>server.close(resolve));}
})().catch(e=>{console.error(e);process.exitCode=1;});
